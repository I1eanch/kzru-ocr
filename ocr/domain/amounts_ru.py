"""Денежные суммы в документах РК: цифры, пропись, сверка пар.

Характерный шаблон договоров РК: ``500 000 (пятьсот тысяч) тенге`` —
число, затем в скобках сумма прописью. Расхождение цифр и прописи —
типичная OCR-ошибка, которую надо ловить.
"""

from __future__ import annotations

import re
from dataclasses import dataclass

from .amounts_kk import words_to_number as _words_to_number_kk

_UNITS = {
    "ноль": 0,
    "один": 1, "одна": 1, "одно": 1, "одни": 1,
    "два": 2, "две": 2,
    "три": 3, "четыре": 4, "пять": 5, "шесть": 6, "семь": 7,
    "восемь": 8, "девять": 9, "десять": 10,
    "одиннадцать": 11, "двенадцать": 12, "тринадцать": 13,
    "четырнадцать": 14, "пятнадцать": 15, "шестнадцать": 16,
    "семнадцать": 17, "восемнадцать": 18, "девятнадцать": 19,
}
_TENS = {
    "двадцать": 20, "тридцать": 30, "сорок": 40, "пятьдесят": 50,
    "шестьдесят": 60, "семьдесят": 70, "восемьдесят": 80, "девяносто": 90,
}
_HUNDREDS = {
    "сто": 100, "двести": 200, "триста": 300, "четыреста": 400,
    "пятьсот": 500, "шестьсот": 600, "семьсот": 700,
    "восемьсот": 800, "девятьсот": 900,
}
_MULT = {
    "тысяча": 10**3, "тысячи": 10**3, "тысяч": 10**3, "тысячей": 10**3,
    "миллион": 10**6, "миллиона": 10**6, "миллионов": 10**6, "миллионе": 10**6,
    "миллиард": 10**9, "миллиарда": 10**9, "миллиардов": 10**9, "миллиарде": 10**9,
    "триллион": 10**12, "триллиона": 10**12, "триллионов": 10**12,
}
# Служебные слова, которые не ломают числовую группу.
_IGNORE = {"и", "тенге", "теңге", "тг", "kzt", "₸", "тиын", "тийын"}

# Число: разрядные группы через пробел/точку либо сплошные цифры + копейки.
# Разделители разрядов и пробелы вокруг валюты: space, NBSP, narrow NBSP,
# thin space; в разрядных группах допускается также точка.
_SP = "    "
_NUM = rf"\d{{1,3}}(?:[{re.escape(_SP)}.]\d{{3}})+|\d+"
_DEC = r"(?:,\d{1,2})?"
_CCY = r"(?:тенге|теңге|тг|kzt|₸)"
_LETTER = r"[A-Za-zА-Яа-яЁёӘәІіҢңҒғҮүҰұҚқӨөҺһ]"

# Связка между частями суммы В ПРЕДЕЛАХ СТРОКИ.
_SAME_LINE = rf"[{re.escape(_SP)}]*"

# Связка, допускающая не более одного перевода строки. OCR переносит строку
# где угодно, и запись «500 000\n(пятьсот тысяч) тенге» — обычное дело.
#
# Но сама по себе она опасна: «согласно пункту 5\nТенге перечисляются» дало
# бы сумму 5, а «ДОГОВОР № 15\n(далее — Договор)» — ложное расхождение с
# прописью. Поэтому через перенос связываются только те совпадения, у
# которых есть независимый признак денежной записи: либо число само выглядит
# денежным (разрядные группы или копейки), либо пропись рядом читается как
# число. Условия проверяются в `find_amounts` и `find_amount_pairs`.
_GAP = rf"[{re.escape(_SP)}]*(?:\n[{re.escape(_SP)}]*)?"

# Денежная форма числа: разрядные группы либо копейки. Одиночное «5» такой
# формы не имеет и через перенос строки с валютой не связывается.
_NUM_MONEY = rf"\d{{1,3}}(?:[{re.escape(_SP)}.]\d{{3}})+(?:,\d{{1,2}})?|\d+,\d{{1,2}}"

# «число [валюта] (пропись)» — пропись обязана содержать хотя бы одну букву.
_PAIR_RE = re.compile(
    rf"(?P<digits>{_NUM}{_DEC})"
    rf"(?:{_GAP}{_CCY})?"
    rf"{_GAP}\((?=[^)]*{_LETTER})(?P<words>[^)]*)\)",
    re.IGNORECASE,
)

# То же, но разрядные группы числа могут быть разорваны переносом строки:
# «3 700\n000 (три миллиона семьсот тысяч) тенге». Такая склейка опасна сама
# по себе — в таблице соседние строки дали бы несуществующее число, — поэтому
# результат этого выражения принимается ТОЛЬКО когда пропись рядом совпала с
# собранным числом. Пропись работает контрольной суммой склейки.
_NUM_ML = rf"\d{{1,3}}(?:[{re.escape(_SP)}.]?\n?[{re.escape(_SP)}.]?\d{{3}})+|\d+"
_PAIR_ML_RE = re.compile(
    rf"(?P<digits>{_NUM_ML}{_DEC})"
    rf"(?:{_GAP}{_CCY})?"
    rf"{_GAP}\((?=[^)]*{_LETTER})(?P<words>[^)]*)\)",
    re.IGNORECASE,
)

# «число [(пропись)] валюта» — денежные величины в пределах одной строки.
_AMOUNT_RE = re.compile(
    rf"(?P<digits>{_NUM}{_DEC})"
    rf"(?:{_SAME_LINE}\([^)]*\))?"
    rf"{_SAME_LINE}{_CCY}",
    re.IGNORECASE,
)

# То же через перенос строки, но только для чисел денежной формы: иначе
# «пункту 5\nТенге» превращалось бы в сумму 5.
_AMOUNT_CROSS_RE = re.compile(
    rf"(?P<digits>{_NUM_MONEY})"
    rf"(?:{_GAP}\([^)]*\))?"
    rf"{_GAP}{_CCY}",
    re.IGNORECASE,
)


_MONEY_FORM_RE = re.compile(rf"\A(?:{_NUM_MONEY})\Z")


def _is_money_form(digits: str) -> bool:
    """Число само по себе выглядит денежным: разрядные группы или копейки.

    Признак того, что запись, собранная через перенос строки, — про деньги,
    а не про номер пункта или документа. «500 000» и «1250,50» денежные,
    «15» — нет.
    """
    return bool(_MONEY_FORM_RE.match(digits))


def words_to_number(s: str) -> int | None:
    """Русские числительные до миллиардов -> int; неизвестное слово -> None."""
    total = 0
    current = 0
    seen = False
    for raw in re.split(r"[\s\-–—]+", s.lower().replace("ё", "е")):
        w = raw.strip(".,;:!?()«»\"'")
        if not w or w in _IGNORE:
            continue
        if w in _UNITS:
            current += _UNITS[w]
        elif w in _TENS:
            current += _TENS[w]
        elif w in _HUNDREDS:
            current += _HUNDREDS[w]
        elif w in _MULT:
            total += (current if current else 1) * _MULT[w]
            current = 0
        else:
            return None
        seen = True
    if not seen:
        return None
    return total + current


def parse_digits(s: str) -> int | None:
    """``"1 250 000"``, ``"1250000"``, ``"1 250 000,00"``, ``"1.250.000"`` -> int тенге.

    Копейки отбрасываются.
    """
    t = s.strip()
    for sp in ("\u00a0", "\u202f", "\u2009", "\u2007"):
        t = t.replace(sp, " ")
    # Копейки после запятой отсекаем.
    if "," in t:
        t = t.split(",", 1)[0]
    # Перенос строки внутри разрядов убирается здесь; допускать его вправе
    # только `_PAIR_ML_RE`, и только под подтверждение прописью.
    t = t.replace("\n", "").replace(" ", "")
    if "." in t:
        head, _, tail = t.rpartition(".")
        if tail.isdigit() and len(tail) == 3 and head.replace(".", "").isdigit():
            t = t.replace(".", "")  # точки — разрядные разделители
        else:
            t = t.split(".", 1)[0]  # десятичная точка — копейки
    if not t.isdigit():
        return None
    return int(t)


@dataclass(slots=True)
class AmountCheck:
    """Пара «цифрами (прописью)» и результат сверки."""

    digits: int
    words: int | None
    raw: str
    ok: bool


def find_amount_pairs(text: str) -> list[AmountCheck]:
    """Найти шаблоны «число (пропись)» и сверить цифры с прописью.

    Пропись распознаётся на русском или казахском: сначала русский парсер,
    при ``None`` — казахский.

    Разбор идёт в два прохода. Первым работает проход со склейкой: он
    допускает перенос строки внутри разрядов числа, но его результат
    принимается, только если пропись совпала с собранным числом. Такая
    склейка без проверки опасна — «500» и «000» в соседних строках таблицы
    дали бы несуществующие 500000, — поэтому пропись выступает контрольной
    суммой: вероятность, что случайная склейка совпадёт с написанной рядом
    суммой, пренебрежимо мала.

    Вторым идёт строгий проход, требующий число целиком в одной строке. Он
    разбирает то, что не взял первый. Порядок именно такой: строгий проход
    дал бы более короткое совпадение («000 (три миллиона…)») и занял бы
    участок, после чего склейка никогда бы не применилась.
    """
    out: list[AmountCheck] = []
    seen: set[tuple[int, int]] = set()

    # Сначала проход со склейкой: он даёт более длинное совпадение, и его
    # результат принимается только при совпавшей прописи. Что он не взял,
    # разбирает строгий проход — иначе строгий занял бы хвост числа
    # («000 (три миллиона…)») и склейка никогда бы не применилась.
    for regex, require_match in ((_PAIR_ML_RE, True), (_PAIR_RE, False)):
        for m in regex.finditer(text):
            span = m.span()
            if any(span[0] < e and s < span[1] for s, e in seen):
                continue  # участок уже разобран предыдущим проходом

            digits = parse_digits(m.group("digits")) or 0
            words = words_to_number(m.group("words"))
            if words is None:
                words = _words_to_number_kk(m.group("words"))
            ok = words is not None and words == digits

            if require_match and not ok:
                continue  # склейка через перенос без подтверждения — не берём

            # Пара, собранная через перенос строки, требует подтверждения,
            # что это вообще запись суммы. Подтверждают двое: читаемая
            # пропись либо денежная форма самого числа.
            #
            # Без этого «ДОГОВОР № 15\n(далее — Договор)» становится парой
            # 15 против нечитаемых слов и даёт ложное расхождение. Но и
            # отбрасывать всё подряд нельзя: «500 000\n(пятьсот тьсяч)» —
            # это настоящая сумма с опечаткой OCR в прописи, и расхождение
            # обязано дойти до клиента, а не потеряться.
            if words is None and "\n" in m.group(0) and not _is_money_form(m.group("digits")):
                continue
            seen.add(span)
            out.append(AmountCheck(digits=digits, words=words, raw=m.group(0), ok=ok))

    return out


def _is_carried_tail(text: str, m: "re.Match[str]") -> bool:
    """Совпадение — доказуемый хвост числа, разорванного переносом строки.

    Признак намеренно узкий: целая часть — ровно три нуля, совпадение стоит
    после перевода строки, а предыдущая строка заканчивается цифрой. Это
    «3 700\\n000 тенге», где «000» — младшие разряды, а не самостоятельная
    величина. Копейки допускаются: «3 700\\n000,00 тенге» — такой же хвост,
    но сравнение строки целиком его пропускало и давало фантомный ноль.

    Шире брать нельзя. Подавление любой трёхзначной группы после строки с
    цифрой убило бы валидное «Договор № 15\\n500 тенге»; подавление по
    ведущему нулю — «0 тенге», которое в справке о задолженности осмысленно.
    Все три нуля подряд самостоятельной суммой не бывают.
    """
    if m.group("digits").split(",", 1)[0] != "000":
        return False
    head = text[: m.start()]
    line_start = head.rstrip(_SP)
    if not line_start.endswith("\n"):
        return False  # совпадение не в начале строки — не перенос
    prev = line_start.rstrip("\n" + _SP)
    return bool(prev) and prev[-1].isdigit()


def find_amounts(text: str) -> list[int]:
    """Все денежные величины: число рядом с ``тенге|теңге|тг|KZT|₸``.

    Два прохода. Первый допускает перенос строки между частями записи, но
    только для чисел денежной формы — с разрядными группами или копейками.
    Иначе «согласно пункту 5\\nТенге перечисляются» давало бы сумму 5.
    Второй разбирает остальное в пределах строки.
    """
    out: list[int] = []
    seen: list[tuple[int, int]] = []

    for regex in (_AMOUNT_CROSS_RE, _AMOUNT_RE):
        for m in regex.finditer(text):
            span = m.span()
            if any(span[0] < e and s < span[1] for s, e in seen):
                continue
            if _is_carried_tail(text, m):
                continue
            v = parse_digits(m.group("digits"))
            if v is not None:
                seen.append(span)
                out.append(v)

    return out
